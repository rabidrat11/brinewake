/**
 * Artefacts and souvenirs.
 *
 * The souvenirs are the heart of the collection game: small, specific, often
 * worthless objects that somebody lost. The artefacts are the mystery.
 */

import type { ItemDef } from '../../items/itemTypes';

/** Shorthand for the many small charming objects that share a shape of entry. */
function souvenir(
  id: string, name: string, value: number, model: string, colors: string[],
  description: string,
  extra: Partial<ItemDef> = {},
): ItemDef {
  return {
    id, name, category: 'souvenir', rarity: 'common', value, mass: 0.3, stack: 10,
    model, colors, donatable: true, discipline: 'archaeology',
    researchValue: Math.max(2, Math.round(value / 12)),
    hasCondition: true, description, ...extra,
  };
}

